import glob
import hashlib
import inspect
import json
import math
import os
import subprocess
import sys
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional

import ragas

from config import log
from ragas_evaluator import ALL_METRICS, JUDGE_MODEL, EMBEDDINGS_MODEL, run_ragas_evaluation, select_metrics

BENCHMARKS_DIR = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "benchmarks"))
RESULTS_DIR = os.path.join(BENCHMARKS_DIR, "results")
REPORT_PATH = os.path.join(BENCHMARKS_DIR, "README.md")
METRIC_NAMES = [m.name for m in ALL_METRICS]

def _git_info() -> Dict[str, Any]:
    """Returns the current commit and whether the working tree has uncommitted changes."""
    try:
        commit = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], text=True).strip()
        dirty = bool(subprocess.check_output(["git", "status", "--porcelain", "--untracked-files=no"], text=True).strip())
        return {"commit": commit, "dirty": dirty}
    except (subprocess.CalledProcessError, FileNotFoundError):
        return {"commit": "unknown", "dirty": None}

def _clean(value: Any) -> Any:
    """Converts NaN (a failed or unscored ragas job) to None so it serialises as JSON null."""
    if isinstance(value, float) and math.isnan(value):
        return None
    return value

def build_record(result, data: List[Dict[str, Any]], dataset: Dict[str, Any], dataset_path: str,
                 strategy: str, label: Optional[str]) -> Dict[str, Any]:
    """
    Builds the JSON record stored for one benchmark run.

    @param result: The ragas EvaluationResult.
    @param data: The evaluation rows that were scored.
    @param dataset: The loaded dataset file.
    @param dataset_path: Path of the dataset file, hashed so runs on different question sets are not compared.
    @param strategy: The GroundingAgent strategy used.
    @param label: Optional free-text label for the run.
    """
    from agent import StrandAgent

    df = result.to_pandas()
    _, skipped = select_metrics(data)
    scored = [name for name in METRIC_NAMES if name in df.columns]
    git = _git_info()
    now = datetime.now(timezone.utc)
    with open(dataset_path, "rb") as f:
        dataset_sha = hashlib.sha256(f.read()).hexdigest()[:12]

    return {
        "run_id": f"{now.strftime('%Y%m%dT%H%M%SZ')}_{git['commit']}",
        "timestamp": now.isoformat(timespec="seconds"),
        "label": label,
        "git": git,
        "dataset": {
            "name": dataset.get("name"),
            "sha256": dataset_sha,
            "samples": len(dataset["samples"]),
            "evaluated": len(data),
        },
        "config": {
            "strategy": strategy,
            "agent_model": inspect.signature(StrandAgent.__init__).parameters["model_id"].default,
            "judge_model": JUDGE_MODEL,
            "embeddings_model": EMBEDDINGS_MODEL,
            "ragas_version": ragas.__version__,
        },
        "metrics_skipped": skipped,
        # 'scored' counts samples with a real score; NaN means the judge call failed for that sample.
        "scores": {
            name: {"mean": _clean(float(df[name].mean())), "scored": int(df[name].notna().sum())}
            for name in scored
        },
        "samples": [
            {
                "user_input": row["user_input"],
                "response": row["response"],
                "scores": {name: _clean(float(row[name])) for name in scored},
            }
            for _, row in df.iterrows()
        ],
    }

def render_report() -> None:
    """Regenerates benchmarks/README.md from every saved run in benchmarks/results/."""
    records = []
    for path in sorted(glob.glob(os.path.join(RESULTS_DIR, "*.json"))):
        with open(path, encoding="utf-8") as f:
            records.append(json.load(f))
    records.sort(key=lambda r: r["timestamp"], reverse=True)

    def cell(record: Dict[str, Any], name: str) -> str:
        score = record["scores"].get(name)
        if score is None:
            return "–"
        if score["mean"] is None:
            return "failed"
        partial = "" if score["scored"] == record["dataset"]["evaluated"] else f" ({score['scored']}/{record['dataset']['evaluated']})"
        return f"{score['mean']:.3f}{partial}"

    lines = [
        "# Benchmarks",
        "",
        "RAGAS scores for the GroundingAgent, one row per run, newest first.",
        "This file is generated by `python src/benchmark.py`; edit `src/benchmark.py`, not this file.",
        "",
        "| Date (UTC) | Commit | Label | Strategy | Dataset | Evaluated | " + " | ".join(METRIC_NAMES) + " |",
        "|---|---|---|---|---|---|" + "---|" * len(METRIC_NAMES),
    ]
    for r in records:
        commit = r["git"]["commit"] + ("-dirty" if r["git"]["dirty"] else "")
        lines.append(
            f"| {r['timestamp'][:16].replace('T', ' ')} | `{commit}` | {r['label'] or ''} | {r['config']['strategy']} "
            f"| {r['dataset']['name']} (`{r['dataset']['sha256']}`) | {r['dataset']['evaluated']}/{r['dataset']['samples']} | "
            + " | ".join(cell(r, name) for name in METRIC_NAMES) + " |"
        )
    if not records:
        lines.append("| _no runs yet_ |" + " |" * (5 + len(METRIC_NAMES)))

    lines += [
        "",
        "`–` = metric skipped (it needs a human-written `reference` for every sample in `benchmarks/dataset.json`).",
        "`(n/m)` = only n of m samples got a score; the rest failed at the judge LLM.",
        "Only compare rows with the same dataset hash: a different hash means the questions or references changed.",
        "",
        "## Running",
        "",
        "```",
        "python src/benchmark.py --label \"short description\"   # run, save to benchmarks/results/, refresh this table",
        "python src/benchmark.py --report-only                   # refresh this table from saved runs",
        "```",
        "",
        "Needs `GOOGLE_API_KEY` and a MongoDB with the dataset's source indexed. Full per-sample scores are in `benchmarks/results/<run_id>.json`.",
        "",
    ]
    with open(REPORT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    log.info(f"Benchmark report written to {REPORT_PATH} ({len(records)} runs).")

async def run_benchmark(dataset_path: str, strategy: str, label: Optional[str]) -> int:
    """
    Runs the dataset through the GroundingAgent, scores it with RAGAS, saves the run and refreshes the report.

    @return: Process exit code (0 on success).
    """
    # Imported here because agent.py connects to MongoDB at import time; --report-only must not need it.
    from evaluation_data import get_evaluation_data, load_dataset

    dataset = load_dataset(dataset_path)
    data = await get_evaluation_data(dataset["samples"], strategy=strategy)
    if not data:
        log.error("No evaluation data generated; nothing to benchmark.")
        return 1

    result = await run_ragas_evaluation(data)
    if result is None:
        log.error("RAGAS evaluation failed; run not saved.")
        return 1

    record = build_record(result, data, dataset, dataset_path, strategy, label)
    if all(score["mean"] is None for score in record["scores"].values()):
        log.error("Every metric failed (check GOOGLE_API_KEY and the judge model); run not saved.")
        return 1

    os.makedirs(RESULTS_DIR, exist_ok=True)
    out_path = os.path.join(RESULTS_DIR, f"{record['run_id']}.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(record, f, indent=2, ensure_ascii=False)
    log.info(f"Benchmark run saved to {out_path}")
    render_report()
    return 0

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run the RAGAS benchmark and record the results in benchmarks/.")
    parser.add_argument("--dataset", default=os.path.join(BENCHMARKS_DIR, "dataset.json"), help="Path to the benchmark dataset JSON.")
    parser.add_argument("--strategy", default="agent", choices=["agent", "llm"], help="GroundingAgent strategy.")
    parser.add_argument("--label", default=None, help="Short description of what this run is testing.")
    parser.add_argument("--report-only", action="store_true", help="Only regenerate benchmarks/README.md.")
    args = parser.parse_args()

    if args.report_only:
        render_report()
        sys.exit(0)

    async def main() -> int:
        code = await run_benchmark(args.dataset, args.strategy, args.label)
        try:
            import litellm
            if hasattr(litellm, 'finish') and callable(litellm.finish):
                await litellm.finish()
        except Exception as e:
            log.error(f"Error calling litellm.finish(): {e}", exc_info=True)
        return code

    sys.exit(asyncio.run(main()))
